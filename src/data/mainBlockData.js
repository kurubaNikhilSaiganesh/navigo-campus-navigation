// ── Query & Filter Helpers ─────────────────────────────────────

export function getRoomsByFloor(floorId) {
  return MAIN_BLOCK_ROOMS.filter((r) => r.floor === floorId);
}

export function getMainBlockRoomById(id) {
  if (!id) return null;
  return MAIN_BLOCK_ROOMS.find((r) => r.id === id || r.code.toLowerCase() === id.toLowerCase() || r.number.toLowerCase() === id.toLowerCase());
}

export function searchMainBlockRooms(query) {
  if (!query || !query.trim()) return MAIN_BLOCK_ROOMS;
  const q = query.trim().toLowerCase();
  return MAIN_BLOCK_ROOMS.filter((r) => {
    const matchName = r.name.toLowerCase().includes(q);
    const matchShort = r.shortName.toLowerCase().includes(q);
    const matchCode = r.code.toLowerCase().includes(q);
    const matchNum = r.number.toLowerCase().includes(q);
    const matchType = r.category.toLowerCase().includes(q) || r.type.toLowerCase().includes(q);
    const matchDept = r.department.toLowerCase().includes(q);
    const matchWing = r.wing.toLowerCase().includes(q);
    const matchYear = r.year ? `${r.year}nd year`.includes(q) || `${r.year}rd year`.includes(q) || `${r.year}th year`.includes(q) || `${r.year} year`.includes(q) || `year ${r.year}`.includes(q) : false;
    const matchDesc = r.description ? r.description.toLowerCase().includes(q) : false;
    const matchAmenities = r.amenities ? r.amenities.some((a) => a.toLowerCase().includes(q)) : false;

    // Keyword special aliases
    if (q === 'classroom' || q === 'classes') return r.type === 'classroom';
    if (q === 'lab' || q === 'labs' || q === 'laboratory') return r.type === 'laboratory';
    if (q === 'seminar' || q === 'seminar hall') return r.type === 'seminar';
    if (q === 'washroom' || q === 'toilet' || q === 'restroom') return r.name.toLowerCase().includes('washroom');
    if (q === 'water' || q === 'water dispenser') return r.name.toLowerCase().includes('water dispenser');
    if (q === 'chairman' || q === "chairman's room") return r.id === 'mb-g-chairman';
    if (q === 'board' || q === 'board room') return r.id === 'mb-g-board';
    if (q === 'store' || q === 'store room') return r.id === 'mb-g-store';
    if (q === 'stairs' || q === 'staircase') return r.type === 'transit';
    if (q === 'lift' || q === 'elevator') return r.name.toLowerCase().includes('lift');

    return matchName || matchShort || matchCode || matchNum || matchType || matchDept || matchWing || matchYear || matchDesc || matchAmenities;
  });
}

// ── Simple Internal Directions Generator ────────────────────────
// Pure building-interior step-by-step logic
// "Ground Floor → Room → Floor 2 → Room 204"
// "Take Staircase A → Floor 2 → Room"
// No fake GPS, no GIS calibration, no fake meters!

export function getInternalDirections(fromId, toId) {
  if (!fromId || !toId) return null;

  // Support special entry point "entrance"
  let fromRoom = null;
  if (fromId === 'entrance' || fromId === 'main_entrance') {
    fromRoom = {
      id: 'entrance',
      floor: 'G',
      name: 'Main Block Entrance (Ground Floor Atrium)',
      shortName: 'Ground Entrance',
      wing: 'Central Atrium',
      category: 'Entrance',
    };
  } else {
    fromRoom = getMainBlockRoomById(fromId);
  }

  const toRoom = getMainBlockRoomById(toId);
  if (!fromRoom || !toRoom) return null;

  if (fromRoom.id === toRoom.id) {
    return {
      sameRoom: true,
      sameFloor: true,
      fromRoom,
      toRoom,
      stepCount: 1,
      floorSummary: fromRoom.floor === 'G' ? 'Ground Floor' : `Floor ${fromRoom.floor}`,
      overviewPath: [fromRoom.name],
      steps: [
        {
          stepNumber: 1,
          type: 'arrive',
          state: 'arrive',
          label: 'ARRIVE',
          title: toRoom.name,
          desc: `You are currently at ${toRoom.name} on Floor ${toRoom.floor}.`,
          floor: fromRoom.floor,
        },
      ],
    };
  }

  const sameFloor = fromRoom.floor === toRoom.floor;
  const steps = [];

  // Determine transit staircase based on destination wing
  const isWest = toRoom.wing ? toRoom.wing.toLowerCase().includes('west') : true;
  const stairName = isWest ? 'Staircase A' : 'Staircase B';
  const wingDirection = isWest ? 'West Wing' : 'East Wing';
  const fromFloorLabel = fromRoom.floor === 'G' ? 'Ground Floor' : `Floor ${fromRoom.floor}`;
  const toFloorLabel = toRoom.floor === 'G' ? 'Ground Floor' : `Floor ${toRoom.floor}`;

  if (sameFloor) {
    steps.push({
      stepNumber: 1,
      type: 'start',
      state: 'start',
      label: 'START',
      title: fromRoom.name,
      desc: fromFloorLabel,
      floor: fromRoom.floor,
    });
    steps.push({
      stepNumber: 2,
      type: 'move',
      state: 'neutral',
      label: 'MOVE',
      title: `Follow corridor to ${toRoom.number || toRoom.shortName}`,
      desc: `Walk along the ${fromFloorLabel} corridor toward the ${wingDirection}.`,
      floor: fromRoom.floor,
    });
    steps.push({
      stepNumber: 3,
      type: 'arrive',
      state: 'arrive',
      label: 'ARRIVE',
      title: toRoom.name,
      desc: toRoom.department || fromFloorLabel,
      floor: toRoom.floor,
    });

    return {
      sameRoom: false,
      sameFloor: true,
      fromRoom,
      toRoom,
      stepCount: 3,
      floorSummary: `Same Level · ${fromFloorLabel}`,
      overviewPath: [fromFloorLabel, toRoom.shortName || toRoom.name],
      steps,
    };
  } else {
    // Inter-floor journey: START → MOVE → CHANGE FLOOR → CONTINUE → ARRIVE
    steps.push({
      stepNumber: 1,
      type: 'start',
      state: 'start',
      label: 'START',
      title: fromRoom.name,
      desc: fromFloorLabel,
      floor: fromRoom.floor,
    });

    steps.push({
      stepNumber: 2,
      type: 'move',
      state: 'neutral',
      label: 'MOVE',
      title: `Walk to ${stairName}`,
      desc: `Follow the ${fromFloorLabel} corridor toward the ${wingDirection}.`,
      floor: fromRoom.floor,
    });

    steps.push({
      stepNumber: 3,
      type: 'floor-change',
      state: 'transition',
      label: 'CHANGE FLOOR',
      title: `Go to Floor ${toRoom.floor}`,
      desc: `Take ${stairName} to Level ${toRoom.floor}.`,
      floor: toRoom.floor,
      fromFloor: fromRoom.floor,
      toFloor: toRoom.floor,
      stairName,
    });

    steps.push({
      stepNumber: 4,
      type: 'continue',
      state: 'neutral',
      label: 'CONTINUE',
      title: `Continue to ${toRoom.shortName || toRoom.name}`,
      desc: `Follow the corridor on Floor ${toRoom.floor} to ${toRoom.number || toRoom.name}.`,
      floor: toRoom.floor,
    });

    steps.push({
      stepNumber: 5,
      type: 'arrive',
      state: 'arrive',
      label: 'ARRIVE',
      title: toRoom.name,
      desc: toRoom.department ? `${toRoom.department}${toRoom.year ? ` · Year ${toRoom.year}` : ''}` : toFloorLabel,
      floor: toRoom.floor,
    });

    return {
      sameRoom: false,
      sameFloor: false,
      fromRoom,
      toRoom,
      stepCount: 5,
      floorSummary: `${fromFloorLabel} → ${toFloorLabel}`,
      transitStair: stairName,
      overviewPath: [fromFloorLabel, stairName, `Floor ${toRoom.floor}`, toRoom.shortName || toRoom.number],
      steps,
    };
  }
}

